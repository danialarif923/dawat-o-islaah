export function getPageNumber(surah, ayah) {
  let lo = 0, hi = hafsPageStarts.length - 1, ans = 0;
  while (lo <= hi) {
    const mid = (lo + hi) >>> 1;
    const [s, a] = hafsPageStarts[mid];
    if (s < surah || (s === surah && a <= ayah)) {
      ans = mid;
      lo = mid + 1;
    } else {
      hi = mid - 1;
    }
  }
  return ans + 1;
}

